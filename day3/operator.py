# true division every value will be in the float

print(155/15)

print(163.7/18)

print(178.8/10.2)

print(-214.6/-34)

print(-7.0/-2)

print(-10/5)


#floor division (how the number is close it rounds to the nearest)

print(155//15)

print(163.7//18)

print(178.8//10.2)

print(type(-7.0//-2))

print(-7.0//-2)

print(-7.0//-2.0)

print(-10//5)

print(-10.8//5)